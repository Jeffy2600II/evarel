import { chromium } from 'playwright'; import fs from 'fs';
import { makeTestUser, API } from './live_user.mjs';
const LIVE='https://evarel-app-forge.nontakorn2600.workers.dev';
const d=process.env.HOME+'/.cache/ms-playwright/chromium_headless_shell-1243/';
const exe=d+fs.readdirSync(d).find(x=>x.startsWith('chrome'))+'/chrome-headless-shell';
const b=await chromium.launch({executablePath:exe});
const user=await makeTestUser('livesmoke');
const ctx=await b.newContext({viewport:{width:412,height:915},timezoneId:'Asia/Bangkok'});
await ctx.addInitScript(([a,s])=>{window.EVAREL_API=a;localStorage.setItem('evarel-session-v2',JSON.stringify(s))},[API,user.session]);
const p=await ctx.newPage(); const errs=[]; p.on('pageerror',e=>errs.push(e.message.slice(0,80)));
await p.goto(LIVE,{waitUntil:'load'}); await p.waitForSelector('[data-tab="all"]',{timeout:15000}); await p.waitForTimeout(2500);
await p.click('[data-act="add"]'); await p.waitForTimeout(400);
await p.click('[data-act="dtype"][data-id="event"]'); await p.waitForSelector('#addForm'); await p.waitForTimeout(500);
const active=await p.evaluate(()=>document.activeElement?.className||'(none)');
await p.click('[data-act="dopen"][data-id="rem"]'); await p.waitForTimeout(450);
const chips=await p.locator('.ev-panel[data-key="rem"] [data-act="drem"]').allTextContents();
const pressed=await p.locator('.ev-panel[data-key="rem"] [data-act="drem"][aria-pressed="true"]').allTextContents();
const tbox=await p.locator('#remTime').count();
const hint=await p.locator('[data-act="rem-off"]').count();
console.log('LIVE activeElement:',active);
console.log('LIVE chips:',JSON.stringify(chips.map(s=>s.trim())));
console.log('LIVE pressed:',JSON.stringify(pressed.map(s=>s.trim())));
console.log('LIVE remTime box:',tbox,'| rem-off hint(ไม่มีเวลา+เปิดเตือน... ฉากนี้เป็น event ที่มีเวลา default จึงควรเป็น 0):',hint);
console.log('LIVE pageerror:',JSON.stringify(errs));
await b.close(); await user.cleanup();
