import { chromium } from 'playwright'; import fs from 'fs';
import { makeTestUser, openAsUser, seedItems, APP_ORIGIN } from './live_user.mjs';
const d=process.env.HOME+'/.cache/ms-playwright/chromium_headless_shell-1243/';
const exe=d+fs.readdirSync(d).find(x=>x.startsWith('chrome'))+'/chrome-headless-shell';
const b=await chromium.launch({executablePath:exe});
const user=await makeTestUser('tboxprobe'); await seedItems(user.session,[]);
const ctx=await openAsUser(b,user,{colorScheme:'light'}); const p=await ctx.newPage();
const errs=[]; p.on('pageerror',e=>errs.push(String(e)));
await p.goto(APP_ORIGIN+'/index.html'); await p.waitForTimeout(2600);
await p.click('[data-act="add"]'); await p.waitForTimeout(400);
await p.click('[data-act="dtype"][data-id="task"]'); await p.waitForSelector('#addForm'); await p.waitForTimeout(400);
await p.click('[data-act="dopen"][data-id="rem"]'); await p.waitForTimeout(400);
await p.evaluate(()=>{window._ev={input:0,change:0,rf:0};document.addEventListener('input',()=>window._ev.input++,true);document.addEventListener('change',e=>{window._ev.change++;if(e.target.closest&&e.target.closest('.ev-tbox'))window._ev.rf++},true)});
await p.fill('#remTime','07:30'); await p.waitForTimeout(300);
const afterFill=await p.evaluate(()=>({label:[...document.querySelectorAll('.ev-tbox-t')].map(x=>x.textContent),val:document.querySelector('#remTime')?.value,ev:{...window._ev}}));
await p.click('[data-act="remadd"]'); await p.waitForTimeout(500);
const afterAdd=await p.evaluate(()=>({tags:[...document.querySelectorAll('.ev-rem-tag')].map(x=>x.textContent.trim()),tboxes:[...document.querySelectorAll('.ev-tbox-t')].map(x=>x.textContent),panelOpen:document.querySelector('.ev-panel[data-key="rem"]')?.dataset.open}));
console.log(JSON.stringify({afterFill,afterAdd,errs}));
await b.close();
